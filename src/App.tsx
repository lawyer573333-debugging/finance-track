function BudgetsView({ budgets, setBudgets, transactions, settings }: any) {
  const [newCat, setNewCat] = useState(settings.categories.expense[0] || '');
  const [newLim, setNewLim] = useState('');
  
  const addBudget = () => {
    if(!newCat || !newLim) return;
    setBudgets((prev: Budget[]) => [...prev.filter(b=>b.category !== newCat), {category: newCat, limit: Number(newLim)}]);
    setNewLim('');
  };

  const currentMonthExp = transactions.filter((t: Transaction) => t.type==='Expense' && isSameMonth(parseISO(t.date), new Date()));

  return (
    <div className="space-y-6">
      <h1 className="text-2xl font-display font-semibold">Budget Planner</h1>
      <div className="bg-slate-850 p-6 rounded-2xl border border-slate-800">
        <div className="flex gap-4 mb-6 form-row">
          <select value={newCat} onChange={e=>setNewCat(e.target.value)} className="bg-slate-900 border border-slate-700 rounded-lg px-4 py-2 flex-1">
             {settings.categories.expense.map((c: string) => <option key={c} value={c}>{c}</option>)}
          </select>
          <input type="number" placeholder="Limit Amount" value={newLim} onChange={e=>setNewLim(e.target.value)} className="bg-slate-900 border border-slate-700 rounded-lg px-4 py-2 w-32" />
          <button onClick={addBudget} className="bg-emerald-500 hover:bg-emerald-600 text-slate-900 px-4 py-2 rounded-lg font-medium">Set</button>
        </div>
        
        <div className="space-y-6">
          {budgets.map((b: Budget) => {
            const spent = currentMonthExp.filter((t: Transaction) => t.category === b.category).reduce((a:number, b:any) => a+b.amount, 0);
            const pct = Math.min((spent / b.limit) * 100, 100);
            const isOver = spent > b.limit;
            return (
              <div key={b.category}>
                <div className="flex justify-between mb-2 text-sm">
                  <span className="font-medium text-slate-200">{b.category}</span>
                  <span>{formatCurrency(spent, settings.currency)} / {formatCurrency(b.limit, settings.currency)}</span>
                </div>
                <div className="h-2 w-full bg-slate-700 rounded-full overflow-hidden">
                  <div className={cn("h-full transition-all text-right", isOver ? 'bg-coral-500' : pct > 80 ? 'bg-amber-500' : 'bg-emerald-500')} style={{width: `${pct}%`}}></div>
                </div>
              </div>
            );
          })}
        </div>
      </div>
    </div>
  );
}

