export type TransactionType = 'Income' | 'Expense';
export type PaymentMethod = 'Cash' | 'Bank Transfer' | 'Credit Card' | 'Debit Card' | 'Mobile Wallet' | 'Cheque' | 'Other';

export interface Transaction {
  id: string;
  type: TransactionType;
  amount: number;
  category: string;
  title: string;
  date: string; // ISO
  paymentMethod: PaymentMethod;
  notes?: string;
  recurring: boolean;
  recurringFrequency?: 'Daily' | 'Weekly' | 'Monthly' | 'Yearly';
  tags: string[];
}

export interface User { id: string; name: string; email: string; joinedDate: string; }
export interface Budget { category: string; limit: number; }
export interface Task { id: string; title: string; priority: 'Low' | 'Medium' | 'High'; dueDate: string; status: 'Pending' | 'In Progress' | 'Done'; isAutoGenerated?: boolean; }
export interface SettingsConfig { currency: string; dateFormat: string; theme: 'Dark' | 'Light' | 'System'; defaultView: string; alertThreshold: number; budgetAlerts: boolean; categories: { income: string[]; expense: string[] }; }
export interface Notification { id: string; message: string; date: string; read: boolean; type: 'info' | 'warning' | 'success'; }

