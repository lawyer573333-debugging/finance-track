export const formatCurrency = (amount: number, currency: string) => {
  const symbol = currency.split(' ')[1] || '$';
  return `${amount < 0 ? '-' : ''}${symbol}${Math.abs(amount).toLocaleString('en-US', { minimumFractionDigits: 0, maximumFractionDigits: 2 })}`;
};

