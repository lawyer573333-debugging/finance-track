function TransactionModal({ editingTx, settings, onClose, onSave }: any) {
  const [type, setType] = useState<TransactionType>(editingTx ? editingTx.type : 'Expense');
  const [amount, setAmount] = useState(editingTx ? editingTx.amount.toString() : '');
  const [category, setCategory] = useState(editingTx ? editingTx.category : settings.categories.expense[0]);
  const [title, setTitle] = useState(editingTx ? editingTx.title : '');
  const [date, setDate] = useState(editingTx ? editingTx.date.split('T')[0] : format(new Date(), 'yyyy-MM-dd'));
  const [pm, setPm] = useState(editingTx ? editingTx.paymentMethod : 'Cash');
  const [notes, setNotes] = useState(editingTx ? editingTx.notes : '');

  const save = (e: React.FormEvent) => {
    e.preventDefault();
    if(!title || !amount || Number(amount) <= 0) return;
    onSave({
      id: editingTx ? editingTx.id : 'tx-'+Date.now(), type, amount: Number(amount), category, title,
      date: new Date(date).toISOString(), paymentMethod: pm, recurring: false, tags: [], notes
    });
  };

  const cats = type === 'Income' ? settings.categories.income : settings.categories.expense;
  useEffect(() => { if(!editingTx) setCategory(cats[0]); }, [type, cats, editingTx]);

  return (
    <div className="fixed inset-0 bg-slate-950/80 backdrop-blur-sm z-50 flex items-center justify-center p-4">
      <motion.div initial={{scale:0.95, opacity:0}} animate={{scale:1, opacity:1}} exit={{scale:0.95, opacity:0}} className="bg-slate-850 w-full max-w-lg rounded-2xl shadow-2xl border border-slate-700 overflow-hidden">
        <div className="flex justify-between items-center p-6 border-b border-slate-800">
          <h3 className="text-xl font-display font-semibold">{editingTx ? 'Edit' : 'Add'} Transaction</h3>
          <button onClick={onClose}><X className="w-5 h-5 text-slate-400 hover:text-white" /></button>
        </div>
        <form onSubmit={save} className="p-6 space-y-4">
          <div className="flex bg-slate-900 p-1 rounded-lg">
             <button type="button" onClick={()=>setType('Income')} className={cn("flex-1 py-2 text-sm font-medium rounded-md", type === 'Income' ? 'bg-emerald-500 text-slate-900 shadow-sm' : 'text-slate-400')}>Income</button>
             <button type="button" onClick={()=>setType('Expense')} className={cn("flex-1 py-2 text-sm font-medium rounded-md", type === 'Expense' ? 'bg-coral-500 text-white shadow-sm' : 'text-slate-400')}>Expense</button>
          </div>
          <div className="grid grid-cols-2 gap-4">
            <div>
              <label className="block text-sm text-slate-400 mb-1">Amount</label>
              <input required type="number" step="0.01" min="0" value={amount} onChange={e=>setAmount(e.target.value)} className="w-full bg-slate-900 border border-slate-700 rounded-xl px-4 py-3 outline-none focus:border-emerald-500 text-lg font-mono" placeholder="0.00" />
            </div>
            <div>
              <label className="block text-sm text-slate-400 mb-1">Date</label>
              <input required type="date" value={date} max={format(new Date(), 'yyyy-MM-dd')} onChange={e=>setDate(e.target.value)} className="w-full bg-slate-900 border border-slate-700 rounded-xl px-4 py-3 outline-none focus:border-emerald-500" />
            </div>
          </div>
          <div>
            <label className="block text-sm text-slate-400 mb-1">Title</label>
            <input required type="text" maxLength={100} value={title} onChange={e=>setTitle(e.target.value)} className="w-full bg-slate-900 border border-slate-700 rounded-xl px-4 py-3 outline-none focus:border-emerald-500" placeholder="e.g. Groceries" />
          </div>
          <div className="grid grid-cols-2 gap-4">
            <div>
              <label className="block text-sm text-slate-400 mb-1">Category</label>
              <select value={category} onChange={e=>setCategory(e.target.value)} className="w-full bg-slate-900 border border-slate-700 rounded-xl px-4 py-3 outline-none focus:border-emerald-500">
                {cats.map((c: string) => <option key={c} value={c}>{c}</option>)}
              </select>
            </div>
            <div>
              <label className="block text-sm text-slate-400 mb-1">Payment Method</label>
              <select value={pm} onChange={e=>setPm(e.target.value)} className="w-full bg-slate-900 border border-slate-700 rounded-xl px-4 py-3 outline-none focus:border-emerald-500">
                {["Cash", "Bank Transfer", "Credit Card", "Debit Card", "Mobile Wallet", "Cheque", "Other"].map(m=><option key={m} value={m}>{m}</option>)}
              </select>
            </div>
          </div>
          <button type="submit" className={cn("w-full font-bold py-4 rounded-xl transition-all text-lg mt-4 shadow-lg", type === 'Income' ? 'bg-emerald-500 hover:bg-emerald-600 text-slate-900 shadow-emerald-500/20' : 'bg-coral-500 hover:bg-coral-600 text-white shadow-coral-500/20')}>
            {editingTx ? 'Save Changes' : 'Add Transaction'}
          </button>
        </form>
      </motion.div>
    </div>
  );
}

